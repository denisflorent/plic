#!/bin/bash
# install-release.sh
#
# Archives, signs, verifies and installs Plic into /Applications, keeping the
# dSYM so a crash in the installed build can still be symbolicated.
#
# Why this exists: the Help book is only served to the app LaunchServices has
# registered for the bundle identifier, which is the copy in /Applications. A
# development build sharing im.plic never gets its own book, so anything
# touching Relay.help has to be installed before it can be looked at.
#
# The development build stays the right tool for everything else — it builds in
# a fraction of the time and, unlike this one, produces crash reports with
# function names and line numbers.

set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO"

WORK="$(mktemp -d)"
SYMBOLS="$REPO/.symbols"
trap 'rm -rf "$WORK"' EXIT

TEAM="7SM2WF75M4"

VERSION=$(grep -m1 -oE 'MARKETING_VERSION = [0-9.]+' Relay.xcodeproj/project.pbxproj | sed 's/.*= //')
BUILD=$(grep -m1 -oE 'CURRENT_PROJECT_VERSION = [0-9]+' Relay.xcodeproj/project.pbxproj | sed 's/.*= //')
echo "==> Plic $VERSION ($BUILD)"

cat > "$WORK/ExportOptions.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>method</key><string>developer-id</string>
    <key>teamID</key><string>$TEAM</string>
    <key>signingStyle</key><string>automatic</string>
    <key>destination</key><string>export</string>
</dict>
</plist>
PLIST

echo "==> Archiving"
xcodebuild archive -project Relay.xcodeproj -scheme Relay -configuration Release \
    -destination 'platform=macOS,arch=arm64' -archivePath "$WORK/Plic.xcarchive" \
    -clonedSourcePackagesDirPath .spm-cache -derivedDataPath .derived \
    -allowProvisioningUpdates CODE_SIGN_STYLE=Automatic "DEVELOPMENT_TEAM=$TEAM" \
    > "$WORK/archive.log" 2>&1 \
  || { grep -E 'error:|ARCHIVE FAILED' "$WORK/archive.log" | head -5; exit 1; }

echo "==> Exporting"
xcodebuild -exportArchive -archivePath "$WORK/Plic.xcarchive" \
    -exportOptionsPlist "$WORK/ExportOptions.plist" -exportPath "$WORK/export" \
    -allowProvisioningUpdates > "$WORK/export.log" 2>&1 \
  || { grep -iE 'error' "$WORK/export.log" | head -5; exit 1; }

APP="$WORK/export/Plic.app"

# The help indexes are generated by a build phase into TARGET_BUILD_DIR. They
# have gone missing from a release once already, and the only symptom is a Help
# window that opens blank, so check rather than assume.
INDEX="$APP/Contents/Resources/Relay.help/Contents/Resources/en.lproj/Plic.helpindex"
[ -f "$INDEX" ] || { echo "FAIL: help index missing from the export"; exit 1; }
SIZE=$(stat -f %z "$INDEX")
[ "$SIZE" -gt 10000 ] || { echo "FAIL: help index is $SIZE bytes — an empty index is ~6.8 KB"; exit 1; }
echo "==> Help index present ($SIZE bytes)"

codesign --verify --deep --strict "$APP" || { echo "FAIL: signature"; exit 1; }
echo "==> Signature valid"

# Keep the dSYM. A release binary crashes with addresses, not function names,
# and without this the report cannot be read back into source.
mkdir -p "$SYMBOLS"
DSYM_SRC="$WORK/Plic.xcarchive/dSYMs"
if [ -d "$DSYM_SRC" ]; then
    rm -rf "$SYMBOLS/$VERSION-$BUILD"
    cp -R "$DSYM_SRC" "$SYMBOLS/$VERSION-$BUILD"
    echo "==> dSYMs kept in .symbols/$VERSION-$BUILD"
else
    echo "WARN: no dSYMs in the archive — a crash here will not symbolicate"
fi

echo "==> Installing"
pkill -9 -f '/Applications/Plic.app/Contents/MacOS/Plic' 2>/dev/null || true
sleep 1
rm -rf /Applications/Plic.app
cp -R "$APP" /Applications/
codesign --verify --strict /Applications/Plic.app || { echo "FAIL: signature after copy"; exit 1; }

# Help Viewer keys its materialised copy of the book by marketing version and
# will otherwise serve the previous one indefinitely.
killall "Help Viewer" HelpViewer helpd 2>/dev/null || true
rm -rf ~/Library/Group\ Containers/group.com.apple.helpviewer.content/Library/Caches
/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister \
    -f /Applications/Plic.app

# Leaving release products in DerivedData registers a second copy under the same
# bundle identifier, which is how a stale help book and a stale icon each got
# served for a day.
rm -rf .derived/Build/Products/Release .derived/Build/Intermediates.noindex/ArchiveIntermediates

echo "==> Installed Plic $VERSION ($BUILD)"
open /Applications/Plic.app
